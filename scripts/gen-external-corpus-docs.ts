/**
 * External corpus observation projection.
 *
 * The canonical data lives in `data/external-corpora/`. These documents are
 * generated from it and must never be hand-edited. The projection indexes
 * observed items; it never restates their content.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import { groupItemsByClass, observationDefects } from "../src/domain/external-corpus";
import { loadExternalCorpora } from "../src/lib/external-corpus-registry";

const OUT_DIR = join(process.cwd(), "docs", "external-corpora");

const CLASS_LABELS: Record<string, string> = {
  "foundation-document": "Foundation documents",
  workbook: "Workbooks",
  spreadsheet: "Spreadsheets",
  probe: "Probe artifacts",
  other: "Other items",
};

function esc(value: string): string {
  return value.replace(/\|/g, "\\|");
}

function bytes(size: number | null): string {
  return size === null ? "—" : `${size.toLocaleString("en-US")}`;
}

function observationDoc(): string {
  const records = loadExternalCorpora();
  const lines: string[] = [
    "<!-- Generated by scripts/gen-external-corpus-docs.ts from data/external-corpora/.",
    "     Edit the data, not this file. -->",
    "",
    "# Observed external corpora",
    "",
    "An observation records what was seen in an external location at a point in time. It grants no",
    "authority to anything it lists. See `NON_PROMOTION_BOUNDARY.md`.",
    "",
  ];

  for (const record of records) {
    lines.push(
      `## ${record.corpus_id} — ${esc(record.corpus_title)}`,
      "",
      `Authority class: **${record.authority_class}**.`,
      "",
      `Observed ${record.observed_at} by ${esc(record.observed_by)}. Location class:`,
      `${record.location_class}. Items observed: ${record.item_count}.`,
      "",
      `Method: ${esc(record.observation_method)}`,
      "",
      `Independence: ${esc(record.observation_independence ?? "Not stated.")}`,
      "",
      "### Non-authority",
      "",
      esc(record.non_authority_statement),
      "",
    );

    for (const [cls, items] of groupItemsByClass(record.items)) {
      lines.push(
        `### ${CLASS_LABELS[cls] ?? cls}`,
        "",
        "| Item | Declared ID | Declared status | Bytes | Modified | Read state |",
        "| --- | --- | --- | --- | --- | --- |",
        ...items.map(
          (item) =>
            `| ${esc(item.item_name)} | ${item.declared_document_id ?? "—"} | ${esc(item.declared_status ?? "—")} | ${bytes(item.byte_size)} | ${item.modified_at ?? "—"} | ${item.read_state} |`,
        ),
        "",
      );
    }

    if (record.declared_but_absent.length > 0) {
      lines.push(
        "### Declared by the corpus, absent at observation",
        "",
        "| Declared ID | Declared title | Cited by | Presence |",
        "| --- | --- | --- | --- |",
        ...record.declared_but_absent.map(
          (absent) =>
            `| ${absent.declared_document_id} | ${esc(absent.declared_title)} | ${absent.cited_by.join(", ")} | ${absent.presence} |`,
        ),
        "",
        ...record.declared_but_absent
          .filter((absent) => absent.note)
          .map((absent) => `- **${absent.declared_document_id}** — ${esc(absent.note ?? "")}`),
        "",
      );
    }

    if (record.subsequent_disposition) {
      lines.push(
        "### Subsequent disposition",
        "",
        "Appended after the observation. The observation above is unchanged and remains true about",
        "what was seen and when. A disposition describes handling only; it confers no authority.",
        "",
        esc(record.subsequent_disposition),
        "",
      );
    }

    lines.push("### Non-effects", "", ...record.non_effects.map((entry) => `- ${entry}`), "");
  }

  return lines.join("\n");
}

function boundaryDoc(): string {
  const records = loadExternalCorpora();
  const lines: string[] = [
    "<!-- Generated by scripts/gen-external-corpus-docs.ts from data/external-corpora/.",
    "     Edit the data, not this file. -->",
    "",
    "# Non-promotion boundary",
    "",
    "Every corpus recorded under `data/external-corpora/` carries the fixed authority class",
    "**HISTORICAL_REFERENCE — NON-CONTROLLING**. Observation is not promotion, and the record",
    "format has no field capable of expressing promotion.",
    "",
    "## What an observation record cannot do",
    "",
    "- It cannot make an observed item canonical, accepted, approved, adopted, or implemented.",
    "- It cannot record an owner decision, close a finding, or open a gate.",
    "- It cannot create a program, phase, maturity level, requirement, or repository.",
    "- It cannot be cited as authority for any statement about the observed material.",
    "- It cannot establish that an observed corpus and this repository inherit from each other.",
    "",
    "## Per-corpus statements",
    "",
  ];

  for (const record of records) {
    lines.push(
      `### ${record.corpus_id} — ${esc(record.corpus_title)}`,
      "",
      esc(record.non_authority_statement),
      "",
      ...record.non_effects.map((entry) => `- ${entry}`),
      "",
    );
  }

  lines.push(
    "## Ageing",
    "",
    "Each record ages from its own observation timestamp. A container may change after it was",
    "observed; re-observation is required before the record is relied on.",
    "",
  );

  return lines.join("\n");
}

function main() {
  const records = loadExternalCorpora();
  const defects = records.flatMap((record) => observationDefects(record));
  if (defects.length > 0) {
    console.error("Refusing to project a defective observation record:");
    for (const defect of defects) console.error(`  - ${defect}`);
    process.exit(1);
  }

  mkdirSync(OUT_DIR, { recursive: true });
  writeFileSync(join(OUT_DIR, "SSLS_3.0_FOUNDATION_OBSERVATION.md"), observationDoc(), "utf8");
  writeFileSync(join(OUT_DIR, "NON_PROMOTION_BOUNDARY.md"), boundaryDoc(), "utf8");

  const items = records.reduce((total, record) => total + record.items.length, 0);
  console.log(
    `External corpora: projected ${records.length} observation(s) covering ${items} items into 2 documents.`,
  );
}

main();
