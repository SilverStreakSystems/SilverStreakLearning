/**
 * SSLS 3.0 canon projection.
 *
 * The canonical data lives in `data/ssls-3.0/canon.json`. These documents are
 * generated from it and must never be hand-edited. The twelve foundation
 * documents themselves are authored sources and are never written here.
 *
 * The projection indexes. It confers nothing.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import {
  authorizedDocuments,
  canonicalStatusCounts,
  decisionsByPriority,
  documentsMissingReviewClass,
  reconstructedDocuments,
  type DecisionPriority,
} from "../src/domain/ssls-3-0/canon";
import { loadCanon } from "../src/lib/ssls-3-0-registry";

const OUT_DIR = join(process.cwd(), "docs", "ssls-3.0");

const HEADER = [
  "<!-- Generated by scripts/gen-ssls-3-0-docs.ts from data/ssls-3.0/canon.json.",
  "     Edit the data, not this file. -->",
  "",
];

const PRIORITY_LABEL: Record<DecisionPriority, string> = {
  "1": "Priority 1 — blocks everything downstream",
  "2": "Priority 2",
  "3": "Priority 3",
  unranked: "Unranked — the foundation package states no priority",
};

function esc(value: string): string {
  return value.replace(/\|/g, "\\|");
}

function canonIndexDoc(): string {
  const record = loadCanon();
  const statusCounts = canonicalStatusCounts(record);
  const authorized = authorizedDocuments(record);
  const reconstructed = reconstructedDocuments(record);
  const missingReviewClass = documentsMissingReviewClass(record);

  const lines: string[] = [
    ...HEADER,
    `# ${esc(record.canon_title)}`,
    "",
    `Record: \`${record.canon_id}\`. Authority class: **${record.authority_class}**.`,
    "",
    record.non_authority_statement,
    "",
    "## Clean-slate position",
    "",
    record.clean_slate_statement,
    "",
    "## Standing counts",
    "",
    "| Measure | Count |",
    "|---|---|",
    `| Documents registered | ${record.documents.length} |`,
    `| Documents carrying authority | ${authorized.length} |`,
    `| Documents reconstructed rather than transcribed | ${reconstructed.length} |`,
    `| Documents not stating a review class | ${missingReviewClass.length} |`,
    `| Open owner decisions | ${record.open_decisions.length} |`,
    `| Unresolved items carried forward | ${record.unresolved_items.length} |`,
    "",
  ];

  lines.push("Lifecycle status distribution:", "", "| Status | Documents |", "|---|---|");
  for (const [status, count] of [...statusCounts].sort((a, b) => a[0].localeCompare(b[0]))) {
    lines.push(`| ${status} | ${count} |`);
  }
  lines.push("");

  lines.push(
    "## Documents",
    "",
    "| ID | File | Controls | Status | Provenance | Authorizing decision | Open decisions |",
    "|---|---|---|---|---|---|---|",
  );
  const ordered = [...record.documents].sort((a, b) => a.file_name.localeCompare(b.file_name));
  for (const doc of ordered) {
    lines.push(
      `| ${doc.document_id} | [\`${doc.file_name}\`](${doc.file_name}) | ${esc(doc.controlled_concept)} | ${doc.canonical_status} | ${doc.provenance} | ${doc.authorizing_decision ?? "none"} | ${doc.open_decision_ids.length} |`,
    );
  }
  lines.push("");

  lines.push(
    "## Review class",
    "",
    "Review class is stated by each document about itself. Where a document states none, that",
    "absence is recorded rather than filled in by inference.",
    "",
    "| ID | Review class |",
    "|---|---|",
  );
  for (const doc of ordered) {
    lines.push(
      `| ${doc.document_id} | ${doc.review_class ? esc(doc.review_class) : "**none stated**"} |`,
    );
  }
  lines.push("");

  if (reconstructed.length > 0) {
    lines.push(
      "## Reconstructions",
      "",
      "A reconstruction was composed from statements cited elsewhere because no source item existed.",
      "It awaits owner confirmation and carries no authority in the meantime.",
      "",
    );
    for (const doc of reconstructed) {
      lines.push(`### ${doc.document_id} — ${esc(doc.title)}`, "", doc.provenance_note ?? "", "");
    }
  }

  if (record.unresolved_items.length > 0) {
    lines.push(
      "## Unresolved items",
      "",
      "Carried forward rather than silently corrected. Each routes to an owner decision.",
      "",
    );
    for (const item of record.unresolved_items) {
      lines.push(`### ${item.item_id}`, "", item.summary, "", "Positions on the record:", "");
      for (const position of item.positions) {
        lines.push(`- ${position}`);
      }
      lines.push("", `Routed to: \`${item.routed_to}\`.`, "");
    }
  }

  lines.push("## Non-effects", "");
  for (const effect of record.non_effects) {
    lines.push(`- ${effect}`);
  }
  lines.push("");

  return lines.join("\n");
}

function openDecisionsDoc(): string {
  const record = loadCanon();
  const grouped = decisionsByPriority(record);

  const lines: string[] = [
    ...HEADER,
    "# SSLS 3.0 — open owner decisions",
    "",
    `Every owner decision the foundation package leaves open: **${record.open_decisions.length}** in total.`,
    "",
    "Listing a decision does not answer it, rank it beyond what the package itself states, or defer",
    "it. Only the owner records a decision.",
    "",
  ];

  for (const priority of ["1", "2", "3", "unranked"] as DecisionPriority[]) {
    const decisions = grouped.get(priority);
    if (!decisions || decisions.length === 0) continue;
    lines.push(
      `## ${PRIORITY_LABEL[priority]}`,
      "",
      `${decisions.length} decision${decisions.length === 1 ? "" : "s"}.`,
      "",
      "| ID | Raised by | Decision needed |",
      "|---|---|---|",
    );
    for (const decision of decisions) {
      lines.push(
        `| ${decision.decision_id} | ${decision.source_document_id} | ${esc(decision.question)} |`,
      );
    }
    lines.push("");
  }

  lines.push("## By source document", "", "| Document | Open decisions |", "|---|---|");
  const ordered = [...record.documents].sort((a, b) => a.file_name.localeCompare(b.file_name));
  for (const doc of ordered) {
    lines.push(
      `| ${doc.document_id} — ${esc(doc.title)} | ${doc.open_decision_ids.join(", ") || "none"} |`,
    );
  }
  lines.push("");

  return lines.join("\n");
}

function main(): void {
  mkdirSync(OUT_DIR, { recursive: true });
  writeFileSync(join(OUT_DIR, "CANON_INDEX.md"), canonIndexDoc(), "utf8");
  writeFileSync(join(OUT_DIR, "OPEN_DECISIONS.md"), openDecisionsDoc(), "utf8");
  process.stdout.write("Wrote docs/ssls-3.0/CANON_INDEX.md and docs/ssls-3.0/OPEN_DECISIONS.md\n");
}

main();
