/**
 * Wave 0 authority and implementation snapshot generator.
 *
 * Controlling source: `data/product-definition-assurance/wave0-declaration.json`.
 * Everything written here is a projection of that declaration plus the live
 * repository inventories. The projection is never controlling and never
 * records an owner disposition.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import {
  DECLARATION_PATH,
  SNAPSHOT_PATH,
  buildWave0Inventories,
  fingerprintDeclaredInputs,
  loadWave0Declaration,
  validateWave0Declaration,
} from "../src/lib/wave0-snapshot";

const DOC_DIR = join(process.cwd(), "docs", "product-definition-assurance");
const DATA_DIR = join(process.cwd(), "data", "product-definition-assurance", "generated");

const MARKER =
  "<!-- Generated by scripts/gen-wave0-snapshot.ts. Edit the declaration, not this file. -->";

function esc(value: string): string {
  return value.replace(/\|/g, "\\|");
}

function bullets(items: string[]): string[] {
  return items.length > 0 ? items.map((item) => `- ${item}`) : ["- None recorded."];
}

function writeDoc(name: string, lines: string[]): string {
  mkdirSync(DOC_DIR, { recursive: true });
  writeFileSync(join(DOC_DIR, name), `${[MARKER, ...lines].join("\n").trimEnd()}\n`);
  return `docs/product-definition-assurance/${name}`;
}

function main() {
  const declaration = loadWave0Declaration();
  const issues = validateWave0Declaration(declaration);

  if (issues.length > 0) {
    console.error("Wave 0 declaration failed validation. Nothing written.");
    for (const issue of issues) console.error(`  ${issue.code}: ${issue.detail}`);
    process.exit(1);
  }

  const inventories = buildWave0Inventories();
  const fingerprint = fingerprintDeclaredInputs(declaration.declared_inputs);

  const snapshot = {
    generated_by: "scripts/gen-wave0-snapshot.ts",
    controlling_source: DECLARATION_PATH,
    authority_note:
      "Generated projection. Candidate authority only. Records no disposition and closes no gate.",
    declaration,
    inventories,
    input_fingerprint: fingerprint,
  };

  mkdirSync(DATA_DIR, { recursive: true });
  writeFileSync(join(process.cwd(), SNAPSHOT_PATH), `${JSON.stringify(snapshot, null, 2)}\n`);

  const written: string[] = [SNAPSHOT_PATH];

  written.push(
    writeDoc("WAVE0_SNAPSHOT.md", [
      `# Wave 0 — authority and implementation snapshot (${declaration.snapshot_id} v${declaration.snapshot_version})`,
      "",
      `Controlling source: \`${DECLARATION_PATH}\`. Controlling decision: ${declaration.controlling_decision}.`,
      `Authority class: ${declaration.authority_class}. Input fingerprint: \`${fingerprint}\`.`,
      "",
      "## Boundary",
      "",
      ...bullets(declaration.boundary),
      "",
      "## State axes in use",
      "",
      "| Axis | Permitted values |",
      "| --- | --- |",
      ...Object.entries(declaration.state_axes).map(
        ([axis, values]) => `| ${axis} | ${esc(values.join(", "))} |`,
      ),
      "",
      "## Preserved program state",
      "",
      "| Subject | State | Source |",
      "| --- | --- | --- |",
      ...declaration.preserved_program_state.map(
        (entry) => `| ${esc(entry.subject)} | ${esc(entry.state)} | \`${entry.source}\` |`,
      ),
      "",
      "## Live repository inventory",
      "",
      "| Measure | Value |",
      "| --- | --- |",
      `| Registered routes | ${inventories.routes.registered} |`,
      `| Route modules on disk | ${inventories.routes.files.total_route_modules} |`,
      `| Historical WP-006 manifest rows | ${inventories.routes.historical_manifest_rows} |`,
      ...Object.entries(inventories.registers)
        .filter(([, value]) => typeof value === "number")
        .map(([key, value]) => `| ${key.replace(/_/g, " ")} | ${value} |`),
      `| Test files | ${inventories.verification.test_files} |`,
      "",
      `Persistence: ${inventories.persistence.backend}`,
      "",
      `Personal data: ${inventories.persistence.personal_data}`,
      "",
      "## Verification commands recorded",
      "",
      ...bullets(inventories.verification.commands.map((command) => `\`${command}\``)),
      "",
      "## Gated future",
      "",
      "| Subject | State |",
      "| --- | --- |",
      ...declaration.gated_future.map((entry) => `| ${esc(entry.subject)} | ${entry.state} |`),
    ]),
  );

  written.push(
    writeDoc("ARTIFACT_GAP_MAP.md", [
      "# Seven-artifact equivalence and gap map",
      "",
      "What already exists, what is missing, and where an extension belongs. Nothing here",
      "adopts a requirement or authorizes a wave.",
      "",
      "| ID | Artifact | Truth | Authority | Implementation | Validation | Claim eligibility |",
      "| --- | --- | --- | --- | --- | --- | --- |",
      ...declaration.artifact_map.map(
        (entry) =>
          `| ${entry.artifact_id} | ${esc(entry.artifact)} | ${entry.states.truth} | ${entry.states.authority} | ${entry.states.implementation} | ${entry.states.validation} | ${entry.states.claim_eligibility} |`,
      ),
      "",
      ...declaration.artifact_map.flatMap((entry) => [
        `## ${entry.artifact_id} — ${entry.artifact}`,
        "",
        `**Already present.** ${entry.present}`,
        "",
        "**Existing canonical sources**",
        "",
        ...bullets(entry.existing_canonical_sources.map((source) => `\`${source}\``)),
        "",
        `**Current evidence:** ${entry.current_evidence.length > 0 ? entry.current_evidence.join(", ") : "None recorded."}`,
        "",
        "**Missing fields**",
        "",
        ...bullets(entry.missing_fields),
        "",
        "**Conflicts**",
        "",
        ...bullets(entry.conflicts),
        "",
        `**Recommended extension.** ${entry.recommended_extension}`,
        "",
      ]),
    ]),
  );

  written.push(
    writeDoc("RECONCILIATION_REPORT.md", [
      "# Source and namespace reconciliation",
      "",
      "Every entry states what was observed and the rule that resolves it. Entries marked",
      "as requiring an owner decision are not resolved by this snapshot.",
      "",
      ...declaration.reconciliation.flatMap((entry) => [
        `## ${entry.entry_id} — ${entry.subject}`,
        "",
        entry.observation,
        "",
        `**Resolution rule.** ${entry.resolution_rule}`,
        "",
        `**Owner decision required:** ${entry.owner_decision_required ? "Yes" : "No"}`,
        "",
        "**Sources**",
        "",
        ...bullets(entry.sources.map((source) => `\`${source}\``)),
        "",
      ]),
    ]),
  );

  written.push(
    writeDoc("OWNER_DISPOSITION_PACKET.md", [
      "# Owner disposition packet — Wave 0",
      "",
      `Recorded disposition: **NONE**. This packet presents choices; it does not record one.`,
      "Only the Founder / Operator may record a disposition, and only in a separate decision record.",
      "",
      ...declaration.disposition_packet.options.flatMap((option) => [
        `## ${option.option_id} — ${option.label}`,
        "",
        option.meaning,
        "",
        "**Consequences**",
        "",
        ...bullets(option.consequences),
        "",
        `**Smallest next action.** ${option.smallest_next_action}`,
        "",
      ]),
      "## What no option does",
      "",
      ...bullets([
        "No option closes Gate A or changes any work-package state.",
        "No option authorizes Waves 1 through 6 by itself.",
        "No option promotes a claim, declares conformance, or permits publication.",
      ]),
    ]),
  );

  written.push(
    writeDoc("WAVE0_MANIFEST.md", [
      "# Wave 0 output manifest",
      "",
      `Snapshot ${declaration.snapshot_id} v${declaration.snapshot_version}. Input fingerprint \`${fingerprint}\`.`,
      "",
      "## Controlling, hand-maintained",
      "",
      ...bullets([
        "`data/product-definition-assurance/wave0-declaration.json`",
        "`data/product-definition-assurance/WAVE0_SNAPSHOT_SCHEMA.json`",
        "`src/lib/wave0-snapshot.ts`",
        "`scripts/gen-wave0-snapshot.ts`",
        "`src/test/product-definition-assurance.test.ts`",
      ]),
      "",
      "## Generated, never hand-edited",
      "",
      ...bullets(written.map((path) => `\`${path}\``)),
      "",
      "## Declared inputs",
      "",
      ...bullets(declaration.declared_inputs.map((input) => `\`${input}\``)),
      "",
      "Regenerate with `bun run gen:wave0` or `bun run check:generated --write`.",
    ]),
  );

  console.log(
    `Wave 0 snapshot written. ${written.length} artifacts, fingerprint ${fingerprint.slice(0, 12)}.`,
  );
}

main();
