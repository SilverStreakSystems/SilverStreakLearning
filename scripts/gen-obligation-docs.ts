/**
 * Generates the WP-038 register projections from the canonical governance data
 * in `data/governance/`. The JSON files are the source of truth; these markdown
 * files are a projection and must never be hand edited.
 *
 * Run: bun run scripts/gen-obligation-docs.ts
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import {
  CONTROL_FAMILIES,
  OBLIGATION_DOMAINS,
  PROHIBITED_OBLIGATION_CLAIMS,
  isGap,
  type ObligationRecord,
} from "../src/domain/obligation";
import {
  loadAuthorities,
  loadObligationContext,
  loadObligations,
} from "../src/lib/obligation-registry";

const OUT = join(process.cwd(), "docs", "wp-038");
mkdirSync(OUT, { recursive: true });

const HEADER =
  "<!-- Generated by scripts/gen-obligation-docs.ts from data/governance/. Edit the data, not this file. -->\n\n";

const authorities = loadAuthorities();
const obligations = loadObligations();
const { conflicts, stale_references, data_triggers } = loadObligationContext();

function write(name: string, body: string) {
  writeFileSync(join(OUT, name), `${HEADER}${body.trimEnd()}\n`, "utf8");
}

const cell = (value: string) => value.replace(/\|/g, "/").replace(/\n/g, " ");

function table(headers: string[], rows: string[][]) {
  return [
    `| ${headers.join(" | ")} |`,
    `|${headers.map(() => "---").join("|")}|`,
    ...rows.map((row) => `| ${row.map(cell).join(" | ")} |`),
  ].join("\n");
}

const DOMAIN_TITLES: Record<string, string> = {
  "student-privacy": "Student privacy",
  accessibility: "Accessibility",
  security: "Security",
  "supply-chain": "Software supply chain",
  interoperability: "Interoperability",
  "ai-governance": "AI governance",
  "records-retention": "Records retention and deletion",
  procurement: "Procurement and attestation",
  "public-surface": "Public surface and claims",
};

function obligationDetail(record: ObligationRecord) {
  return [
    `### ${record.obligation_id} — ${record.title}`,
    "",
    table(
      ["Field", "Value"],
      [
        ["Source", `${record.source_authority} (${record.source_id})`],
        ["Authority type", record.source_type],
        ["Citation", record.citation],
        ["Locator", record.source_url],
        ["Source version", record.source_version],
        ["Verified on", record.verified_on],
        ["Jurisdiction", record.jurisdiction],
        ["Applicability", record.applicability_state],
        ["Trigger", record.applicability_trigger],
        ["Control family", record.control_family],
        ["Control status", record.control_status],
        ["Evidence status", record.evidence_status],
        ["Owning route", record.mapped_work_package],
        ["Review requirement", record.review_requirement ?? "none recorded"],
        ["Review trigger", record.review_trigger],
      ],
    ),
    "",
    `**What the source states.** ${record.source_statement_boundary}`,
    "",
    `**Obligation.** ${record.obligation_summary}`,
    "",
    `**SSLS interpretation.** ${record.ssls_interpretation}`,
    "",
    `**Current phase.** ${record.current_phase_applicability}`,
    "",
    `**Future phase.** ${record.future_phase_applicability}`,
    "",
    `**Required control.** ${record.required_control}`,
    "",
    `**Current control.** ${record.current_control}`,
    "",
    `**Evidence required.** ${record.evidence_requirement} Minimum method: ${record.minimum_evidence_method}`,
    "",
    `**Claim permitted.** ${record.claim_implication}`,
    "",
    `**Claim refused.** ${record.prohibited_claim}`,
    record.notes ? `\n**Note.** ${record.notes}` : "",
  ].join("\n");
}

// README
write(
  "README.md",
  `# WP-038 — Regulatory, Standards & Obligation Baseline

Authority class: candidate. Method: executor-produced, primary-source verified, not independent.
Executed under SSLS-BPP-001 v2.0 (DEC-007) and authorised by DEC-017, which authorises generation
and execution of WP-038 only.

This package records what external authorities require, whether each requirement applies to SSLS
today, what SSLS actually has, and what evidence would be needed. Those are four separate facts and
this package never collapses them into a compliance statement.

## Canonical data

| File | Contents |
|---|---|
| \`data/governance/OBLIGATION_SCHEMA.json\` | Schema for both registers |
| \`data/governance/external-authorities.json\` | ${authorities.length} verified external sources |
| \`data/governance/obligations.json\` | ${obligations.length} interpreted obligations |
| \`data/governance/obligation-context.json\` | Conflicts, stale references, data triggers |

Every document in this directory whose header says so is a projection of that data.

## Documents

| Document | Purpose |
|---|---|
| \`METHOD_AND_LIMITS.md\` | How sources were verified and what that verification cannot support |
| \`JURISDICTION_SCOPE.md\` | Which jurisdictions are in scope and why |
| \`EXTERNAL_AUTHORITY_REGISTER.md\` | The source register |
| \`OBLIGATION_REGISTER.md\` | The full obligation register |
| \`APPLICABILITY_MATRIX.md\` | Obligations by applicability state |
| \`GAP_REGISTER.md\` | Where a required control is absent, partial or specified only |
| \`CONTROL_FAMILY_MAP.md\` | Obligations grouped by control family |
| \`EVIDENCE_REQUIREMENTS.md\` | What evidence each obligation would need |
| \`REVIEW_TRIGGERS.md\` | What event forces a review, and which need qualified review |
| \`CONFLICT_REGISTER.md\` | Source conflicts and ambiguities |
| \`STALE_REFERENCE_REGISTER.md\` | Project references checked against verified current sources |
| \`DATA_TRIGGER_MAP.md\` | Data classes and the obligations each would activate |
| \`REFUSED_CLAIMS.md\` | Wording this baseline will not produce |
| \`CLAIMS_RECONCILIATION.md\` | Claims Register reconciliation |
| \`DEC-012-BRIEF.md\` | Decision brief prepared for the owner |
| \`EXIT_CRITERIA_MATRIX.md\` | Exit criteria and their state |
| \`CLOSURE_RECOMMENDATION.md\` | Recommendation, with limitations preserved |
| \`HANDOFF_TO_WP-007.md\` | What carries forward |
${OBLIGATION_DOMAINS.map((d) => `| \`domain-${d}.md\` | ${DOMAIN_TITLES[d]} obligations |`).join("\n")}

## Boundaries

- No obligation in this register is recorded as met, satisfied or complied with.
- Applicability is not compliance. NOT-APPLICABLE means the trigger has not occurred.
- No product feature, database, live integration, AI feature or personal data was added.
- Only a recorded owner decision closes a gate.
`,
);

// Source register
write(
  "EXTERNAL_AUTHORITY_REGISTER.md",
  `# External authority register

${authorities.length} sources, each verified on ${authorities[0]?.verified_on ?? "n/a"} by direct retrieval from the issuing body or an official mirror.

Source status values: VERIFIED-CURRENT, VERIFIED-HISTORICAL, SUPERSEDED, UNVERIFIED, CONFLICTED.
A source recorded UNVERIFIED or CONFLICTED may not be used to support a determination.

${table(
  ["ID", "Title", "Type", "Citation", "Version", "Jurisdiction", "Status", "Lifecycle"],
  authorities.map((r) => [
    r.source_id,
    r.title,
    r.source_type,
    r.citation,
    r.source_version,
    r.jurisdiction,
    r.source_status,
    r.lifecycle,
  ]),
)}

## Source detail

${authorities
  .map((r) =>
    [
      `### ${r.source_id} — ${r.title}`,
      "",
      `- Issuing body: ${r.issuing_body}`,
      `- Authority type: ${r.source_type}`,
      `- Citation: ${r.citation}`,
      `- Locator: ${r.source_url}`,
      `- Version: ${r.source_version}; effective ${r.source_effective_date}`,
      `- Verified: ${r.verified_on} by ${r.verification_method}`,
      `- Status: ${r.source_status}; lifecycle ${r.lifecycle}`,
      `- Locators used: ${r.section_locators.join("; ")}`,
      "",
      `**What the source states.** ${r.source_statement}`,
      "",
      `**Reproduction boundary.** ${r.reproduction_boundary}`,
      r.notes ? `\n**Note.** ${r.notes}` : "",
    ].join("\n"),
  )
  .join("\n\n")}
`,
);

// Obligation register
write(
  "OBLIGATION_REGISTER.md",
  `# Obligation register

${obligations.length} obligations derived from the source register. Each record separates what the
source states from how SSLS reads it, and separates applicability from control status from evidence
status.

${table(
  ["ID", "Title", "Source", "Applicability", "Control", "Evidence", "Family"],
  obligations.map((r) => [
    r.obligation_id,
    r.title,
    r.source_id,
    r.applicability_state,
    r.control_status,
    r.evidence_status,
    r.control_family,
  ]),
)}

## Obligation detail

${obligations.map(obligationDetail).join("\n\n---\n\n")}
`,
);

// Domain files
for (const domain of OBLIGATION_DOMAINS) {
  const scoped = obligations.filter((r) => r.domain === domain);
  write(
    `domain-${domain}.md`,
    `# ${DOMAIN_TITLES[domain]}

${scoped.length} obligation${scoped.length === 1 ? "" : "s"} in this domain.

${
  scoped.length === 0
    ? "No obligations recorded in this domain."
    : table(
        ["ID", "Title", "Source", "Applicability", "Control status"],
        scoped.map((r) => [
          r.obligation_id,
          r.title,
          r.citation,
          r.applicability_state,
          r.control_status,
        ]),
      )
}

${scoped.map(obligationDetail).join("\n\n---\n\n")}
`,
  );
}

// Applicability matrix
const APPLICABILITY_MEANING: Record<string, string> = {
  "APPLIES-NOW": "The trigger has occurred. The obligation is live for the current build.",
  "APPLIES-AT-PILOT": "Attaches at the first district relationship or real data exchange.",
  "APPLIES-AT-LAUNCH": "Attaches when a hosted service is offered commercially.",
  CONDITIONAL: "Attaches only if a specific capability or data class is introduced.",
  REFERENCE: "Informs design. Creates no obligation on its own.",
  "NOT-APPLICABLE": "The trigger cannot occur in the current or planned scope.",
  UNKNOWN: "Applicability was not determined and must not be assumed either way.",
};

write(
  "APPLICABILITY_MATRIX.md",
  `# Applicability matrix

Applicability answers one question only: has the trigger occurred? It never answers whether SSLS
satisfies the obligation. NOT-APPLICABLE is not a pass.

${Object.entries(APPLICABILITY_MEANING)
  .map(([state, meaning]) => {
    const scoped = obligations.filter((r) => r.applicability_state === state);
    return [
      `## ${state} (${scoped.length})`,
      "",
      meaning,
      "",
      scoped.length === 0
        ? "None recorded."
        : table(
            ["ID", "Title", "Trigger", "Control status"],
            scoped.map((r) => [
              r.obligation_id,
              r.title,
              r.applicability_trigger,
              r.control_status,
            ]),
          ),
    ].join("\n");
  })
  .join("\n\n")}
`,
);

// Gap register
const gaps = obligations.filter(isGap);
write(
  "GAP_REGISTER.md",
  `# Gap register

A gap is an obligation that could attach and whose required control is missing, partial, specified
only, or unknown. Gaps are recorded, not remediated, in this work package.

${gaps.length} gaps recorded.

${table(
  ["ID", "Title", "Applicability", "Control status", "Required control", "Owning route"],
  gaps.map((r) => [
    r.obligation_id,
    r.title,
    r.applicability_state,
    r.control_status,
    r.required_control,
    r.mapped_work_package,
  ]),
)}

## Gaps whose trigger is nearest

${gaps
  .filter((r) => r.applicability_state === "APPLIES-NOW" || r.applicability_state === "CONDITIONAL")
  .map((r) => `- **${r.obligation_id}** ${r.title}. Trigger: ${r.applicability_trigger}`)
  .join("\n")}
`,
);

// Control family map
write(
  "CONTROL_FAMILY_MAP.md",
  `# Control family map

Obligations grouped by the SSLS control family that would satisfy them. Different sources using
different vocabulary map to the same family rather than creating a new one.

${CONTROL_FAMILIES.map((family) => {
  const scoped = obligations.filter((r) => r.control_family === family);
  if (scoped.length === 0) return null;
  return [
    `## ${family} (${scoped.length})`,
    "",
    table(
      ["ID", "Obligation", "Source", "Control status"],
      scoped.map((r) => [r.obligation_id, r.title, r.source_id, r.control_status]),
    ),
  ].join("\n");
})
  .filter(Boolean)
  .join("\n\n")}

## Families with no recorded obligation

${CONTROL_FAMILIES.filter((f) => !obligations.some((r) => r.control_family === f))
  .map((f) => `- ${f}`)
  .join("\n")}
`,
);

// Evidence requirements
write(
  "EVIDENCE_REQUIREMENTS.md",
  `# Evidence requirements

What each obligation would need before any statement about it could be defended. Automated evidence
is never sufficient where the minimum method names human or independent review.

${table(
  ["ID", "Obligation", "Evidence required", "Minimum method", "Current evidence state"],
  obligations.map((r) => [
    r.obligation_id,
    r.title,
    r.evidence_requirement,
    r.minimum_evidence_method,
    r.evidence_status,
  ]),
)}

## Obligations whose evidence cannot be produced internally

${obligations
  .filter((r) => /independent|CPA|certification|conformance testing|legal/i.test(r.minimum_evidence_method))
  .map((r) => `- **${r.obligation_id}** ${r.title} — ${r.minimum_evidence_method}`)
  .join("\n")}
`,
);

// Review triggers
write(
  "REVIEW_TRIGGERS.md",
  `# Review triggers

An SSLS-recorded interpretation is not a legal determination. These obligations carry an explicit
requirement for qualified review before any determination or external statement.

${table(
  ["ID", "Obligation", "Review requirement", "Trigger", "Date rule"],
  obligations.map((r) => [
    r.obligation_id,
    r.title,
    r.review_requirement ?? "none recorded",
    r.review_trigger,
    r.review_date,
  ]),
)}

## Dated external triggers

${obligations
  .filter((r) => /\d{4}-\d{2}-\d{2}/.test(r.review_date))
  .map((r) => `- ${r.review_date} — ${r.obligation_id} ${r.title}`)
  .join("\n")}
`,
);

// Conflict register
write(
  "CONFLICT_REGISTER.md",
  `# Conflict and ambiguity register

Where sources disagreed, could not be retrieved, or could not be dated. None of these is resolved by
assumption.

${table(
  ["ID", "Title", "Sources", "State", "Owner", "Route"],
  conflicts.map((r) => [
    r.conflict_id,
    r.title,
    r.source_ids.join(", "),
    r.state,
    r.resolution_owner,
    r.resolution_route,
  ]),
)}

## Detail

${conflicts
  .map((r) => `### ${r.conflict_id} — ${r.title}\n\n${r.description}\n\nRoute: ${r.resolution_route}`)
  .join("\n\n")}
`,
);

// Stale reference register
write(
  "STALE_REFERENCE_REGISTER.md",
  `# Stale reference register

Existing SSLS references to external authority, checked against the verified current sources.

${table(
  ["ID", "Project reference", "Located in", "Verified current", "Disposition", "Finding"],
  stale_references.map((r) => [
    r.stale_id,
    r.project_reference,
    r.located_in,
    r.verified_current,
    r.disposition,
    r.finding_id ?? "none",
  ]),
)}

${stale_references
  .filter((r) => r.notes)
  .map((r) => `- **${r.stale_id}** ${r.notes}`)
  .join("\n")}
`,
);

// Data trigger map
write(
  "DATA_TRIGGER_MAP.md",
  `# Data trigger map

Each data class that SSLS does not currently hold, and what would attach if it did. Current use is
false for every class in this table; that is the finding, not an omission.

${table(
  ["Data class", "Current use", "Future candidate", "Sensitivity", "Domains activated", "Prerequisite review"],
  data_triggers.map((r) => [
    r.data_class,
    r.current_use ? "yes" : "no",
    r.future_candidate_use ? "yes" : "no",
    r.sensitivity,
    r.obligation_domains.join(", "),
    r.prerequisite_review,
  ]),
)}

## Minimum-necessary position and unresolved questions

${data_triggers
  .map((r) =>
    [
      `### ${r.data_class}`,
      "",
      `- Minimum necessary: ${r.minimum_necessary}`,
      `- Retention question: ${r.retention_question}`,
      `- Disclosure question: ${r.disclosure_question}`,
    ].join("\n"),
  )
  .join("\n\n")}
`,
);

// Refused claims
write(
  "REFUSED_CLAIMS.md",
  `# Refused claims

This baseline produces none of the following, in any wording, on any surface.

${PROHIBITED_OBLIGATION_CLAIMS.map((c) => `- ${c}`).join("\n")}

## Per-obligation refusals

${table(
  ["ID", "Obligation", "Permitted statement", "Refused wording"],
  obligations.map((r) => [
    r.obligation_id,
    r.title,
    r.claim_implication,
    r.prohibited_claim,
  ]),
)}

## Why applicability is not compliance

An obligation recorded NOT-APPLICABLE means its trigger has not occurred. It does not mean SSLS
satisfies it, would satisfy it, or is exempt from it in future. Recording an obligation is not
discharging it, and the register never converts one into the other.
`,
);

console.log(
  `WP-038 docs generated: ${authorities.length} sources, ${obligations.length} obligations, ${gaps.length} gaps.`,
);
