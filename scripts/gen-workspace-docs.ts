/**
 * Generates the governed markdown record for the Enterprise Command Centers &
 * Workspace Experience Architecture v0.1 from the canonical fixtures.
 *
 * Docs are a projection. The fixtures remain the single source of truth.
 * Run: bun run scripts/gen-workspace-docs.ts
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import {
  ACTING_CAPACITIES,
  CROSS_FUNCTIONAL_PROGRAMS,
  GLOBAL_UTILITIES,
  HELP_ENTRIES,
  PROJECTION_PATTERN_CONTRACTS,
  WORKSPACES,
  WORKSPACE_MEMBERSHIPS,
} from "../src/fixtures";
import {
  BLENDED_READINESS_REFUSAL,
  MEMBERSHIP_RULES,
  NOTIFICATION_RULES,
  PRIORITY_FACTORS,
  PROHIBITED_PRIORITY_FACTORS,
  PROHIBITED_WORKSPACE_SIGNALS,
  PROJECTION_ASSEMBLY_STEPS,
  PROJECTION_STEP_META,
  SEARCH_RULES,
  SURFACE_STATES,
  SURFACE_STATE_META,
} from "../src/domain";

const OUT = join(process.cwd(), "docs", "workspaces");
mkdirSync(OUT, { recursive: true });

const HEADER = [
  "<!-- Generated by scripts/gen-workspace-docs.ts. Edit the fixtures, not this file. -->",
  "",
].join("\n");

const list = (items: readonly string[]) => items.map((item) => `- ${item}`).join("\n");

function write(name: string, body: string) {
  writeFileSync(join(OUT, name), `${HEADER}${body.trimEnd()}\n`, "utf8");
}

write(
  "README.md",
  `# Enterprise Command Centers & Workspace Experience Architecture v0.1

Authority class: governed candidate. Nothing in this architecture is approved
for production, for personal data, or for anyone other than the founder or
developer operator.

## Contents

- \`workspace-contract.md\` — the fields every workspace must declare
- \`projection-rule.md\` — the nine-step assembly rule
- \`surface-states.md\` — the eleven governed surface states
- \`global-utilities.md\` — the six cross-workspace utilities
- \`action-center.md\`, \`search.md\`, \`notifications.md\` — utility contracts
- \`capacity-and-membership.md\` — who is acting and what that allows
- \`patterns.md\` — reusable projection patterns and cross-functional programs
- \`refusals.md\` — what this architecture refuses to compute or display
- \`workspace-*.md\` — one record per workspace

## Boundary

Founder and developer operator only. Synthetic records only. No personal data
of any kind. No product-facing AI. Every workspace beyond the operating set is
modeled as future architecture with its gate stated.
`,
);

write(
  "workspace-contract.md",
  `# Workspace contract

A workspace is not a page. It is a governed projection with a declared purpose,
an authorized participant, an acting capacity, a canonical source, and a stated
boundary. A workspace that cannot answer its fundamental question is refused.

Every workspace declares:

- purpose and the fundamental question it answers
- the objects it may read and the objects it must never display
- metrics, each with a source, an interpretation, a prohibited interpretation,
  and the action it triggers
- current boundary and future boundary
- implementation state, held separately from authority
- primary surfaces, each with its own availability

## Refusals inside the contract

${BLENDED_READINESS_REFUSAL}

Prohibited signals:

${list(PROHIBITED_WORKSPACE_SIGNALS)}
`,
);

write(
  "projection-rule.md",
  `# Workspace projection rule

Every workspace surface is assembled in this order. No step may be skipped and
no step may be reordered. A projection is never a source of truth and is never
reusable for a different purpose.

${PROJECTION_ASSEMBLY_STEPS.map(
  (step, index) =>
    `${index + 1}. **${PROJECTION_STEP_META[step].label}** — ${PROJECTION_STEP_META[step].question}`,
).join("\n")}
`,
);

write(
  "surface-states.md",
  `# Surface states

Eleven states. Each states what it means and what the operator does next. A
surface with no governed state is a defect.

${SURFACE_STATES.map(
  (state) =>
    `## ${SURFACE_STATE_META[state].label}\n\n${SURFACE_STATE_META[state].meaning}\n\nNext action: ${SURFACE_STATE_META[state].nextAction}`,
).join("\n\n")}
`,
);

write(
  "capacity-and-membership.md",
  `# Acting capacity and membership

Identity, capacity, membership, and authorization are four different things.
Holding one never implies another.

## Membership rules

${list(MEMBERSHIP_RULES)}

## Capacities on record

${ACTING_CAPACITIES.map(
  (capacity) =>
    `### ${capacity.name} (${capacity.status})\n\n- Policy basis: ${capacity.policyBasis}\n- May decide: ${capacity.decisionRights.join("; ")}\n- Requires other authority: ${capacity.requiresOtherAuthority.join("; ")}\n- Expiry trigger: ${capacity.expiryTrigger}`,
).join("\n\n")}

## Memberships

${WORKSPACE_MEMBERSHIPS.map(
  (membership) =>
    `- **${membership.workspaceId}** / ${membership.capacityId} — ${membership.relationship}. Purpose: ${membership.purpose}. Scope: ${membership.objectScope.join(", ")}.`,
).join("\n")}
`,
);

write(
  "global-utilities.md",
  `# Global utilities

Six utilities cross every workspace. None of them creates a canonical object;
each reads canonical registers and projects.

${GLOBAL_UTILITIES.map(
  (utility) =>
    `## ${utility.name}\n\nRoute: \`${utility.route}\`\n\n${utility.purpose}\n\n- Reads: ${utility.readsCanonicalObjects.join(", ")}\n- Creates canonical objects: none\n- Boundary: ${utility.boundary}`,
).join("\n\n")}
`,
);

write(
  "action-center.md",
  `# Universal Action Center

The Action Center projects obligations already recorded in canonical registers.
It never invents work and never holds state of its own.

## Ordering factors, in priority order

${PRIORITY_FACTORS.map((factor, index) => `${index + 1}. ${factor}`).join("\n")}

## Refused ordering factors

${list(PROHIBITED_PRIORITY_FACTORS)}
`,
);

write(
  "search.md",
  `# Universal search

Authorization happens before retrieval, before counting, and before faceting.
A withheld record must not be inferable from a count, a facet, or a suggestion.

${list(SEARCH_RULES)}
`,
);

write(
  "notifications.md",
  `# Notifications

${list(NOTIFICATION_RULES)}
`,
);

write(
  "patterns.md",
  `# Reusable projection patterns and cross-functional programs

## Patterns

${PROJECTION_PATTERN_CONTRACTS.map(
  (pattern) =>
    `### ${pattern.name} (${pattern.availability})\n\n${pattern.purpose}\n\n- Duplication rule: ${pattern.duplicationRule}\n- Prohibited content: ${pattern.prohibitedContent.join("; ")}`,
).join("\n\n")}

## Cross-functional programs

${CROSS_FUNCTIONAL_PROGRAMS.map(
  (program) => `- **${program.name}** (${program.availability}) — ${program.purpose}`,
).join("\n")}
`,
);

write(
  "help-content.md",
  `# Knowledge and help content

Governing content constrains work. Explanatory content does not and may never
be cited as authority.

${HELP_ENTRIES.map(
  (entry) =>
    `- **${entry.title}** — ${entry.kind}, authority ${entry.authorityClass}, version ${entry.version}. Source: ${entry.source}.`,
).join("\n")}
`,
);

write(
  "refusals.md",
  `# Refusals

This architecture refuses to compute or display the following, in any
workspace, utility, projection, or export.

${BLENDED_READINESS_REFUSAL}

${list(PROHIBITED_WORKSPACE_SIGNALS)}

${list(PROHIBITED_PRIORITY_FACTORS)}

A refusal is a designed property, not a missing feature. Removing one requires
a recorded decision with named authority.
`,
);

for (const workspace of WORKSPACES) {
  write(
    `workspace-${workspace.workspaceId}.md`,
    `# ${workspace.name}

Implementation state: ${workspace.implementationState}

## Fundamental question

${workspace.fundamentalQuestion}

## Purpose

${workspace.purpose}

## Boundaries

- Current: ${workspace.currentBoundary}
- Future: ${workspace.futureBoundary}

## Objects it must never display

${list(workspace.prohibitedObjects)}

## Metrics

${workspace.metrics
  .map(
    (metric) =>
      `### ${metric.name}\n\n- Question answered: ${metric.questionAnswered}\n- Source: ${metric.source}\n- Calculation: ${metric.calculation}\n- Freshness: ${metric.freshness}\n- Interpretation: ${metric.interpretation}\n- Must never be read as: ${metric.prohibitedInterpretation}\n- Action triggered: ${metric.actionTriggered}`,
  )
  .join("\n\n")}

## Primary surfaces

${workspace.primarySurfaces
  .map((surface) => `- **${surface.name}** (${surface.availability}) — ${surface.purpose}`)
  .join("\n")}
`,
  );
}

console.log(`Wrote ${WORKSPACES.length + 11} files to docs/workspaces/`);
